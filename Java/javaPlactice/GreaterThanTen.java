package javaPlactice;

public class GreaterThanTen {
	 public static void main(String[] args) {
	int num = 12;
	
	if(num>10) {
		System.out.println(num + "は10より大きいです");
		}else if(num<10) { 
			System.out.println(num + "は10より小さいです");
		}else if(num==10) {
			System.out.println(num + "は10と同じ数です");
		}
	 }
}
